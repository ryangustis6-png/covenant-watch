// Precompute the covenant watchlist so the dashboard can be served as static files.
// Writes public/watchlist.json (dashboard) and lib/generated-watchlist.js (serverless memo function).
import fs from 'node:fs/promises';
import {parseCSV} from '../lib/csv.js';
import {buildWatchlist} from '../lib/covenants.js';

const root = new URL('../', import.meta.url);
const rows = parseCSV(await fs.readFile(new URL('data/loan_covenants.csv', root), 'utf8'));
const policy = await fs.readFile(new URL('data/documents/loan-policy.txt', root), 'utf8');
const watchlist = buildWatchlist(rows, policy);
if (!watchlist.evidence.leverage?.verified || !watchlist.evidence.dscr?.verified) throw Error('Covenant definitions not found in agreement text');

await fs.mkdir(new URL('public/', root), {recursive: true});
await fs.writeFile(new URL('public/watchlist.json', root), JSON.stringify(watchlist));
await fs.writeFile(new URL('lib/generated-watchlist.js', root),
  `// Generated by scripts/build-watchlist.js — do not edit.\nexport default ${JSON.stringify(watchlist)};\n`);
const s = watchlist.summary;
console.log(`Watchlist built: ${s.borrowers} borrowers, ${s.quarters_evaluated}/${s.rows} quarters evaluated, ${s.breach} breach, ${s.watch} watch, ${s.pass} pass, ${s.review} review.`);
